#!/usr/bin/env node
/**
 * Downloads benchmark exercise photos from Free Exercise DB (public domain,
 * github.com/yuhonas/free-exercise-db), resizes them to 360px wide with macOS
 * `sips`, and writes a static require() map to src/benchmark/photos.ts.
 *
 * Usage: node scripts/benchmark/fetch-photos.mjs
 * Re-run after adding a version whose data.json references new photos.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const versionsDir = join(root, 'src/benchmark/versions');
const outDir = join(root, 'assets/benchmark/img');
const mapFile = join(root, 'src/benchmark/photos.ts');
const BASE = 'https://raw.githubusercontent.com/yuhonas/free-exercise-db/main/exercises';

function collect(node, out) {
  if (Array.isArray(node)) node.forEach((n) => collect(n, out));
  else if (node && typeof node === 'object') {
    if (Array.isArray(node.photos)) node.photos.forEach((p) => out.add(p));
    Object.values(node).forEach((n) => collect(n, out));
  }
}

const paths = new Set();
for (const v of readdirSync(versionsDir)) {
  const f = join(versionsDir, v, 'data.json');
  if (existsSync(f)) collect(JSON.parse(readFileSync(f, 'utf8')), paths);
}

mkdirSync(outDir, { recursive: true });
let fetched = 0;
for (const p of [...paths].sort()) {
  const file = p.replace(/^img\//, '');
  const dest = join(outDir, file);
  if (existsSync(dest)) continue;
  const m = file.match(/^(.*)-(\d)\.jpg$/);
  if (!m) throw new Error(`Unexpected photo name: ${p}`);
  const url = `${BASE}/${encodeURIComponent(m[1])}/${m[2]}.jpg`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} fetching ${url}`);
  writeFileSync(dest, Buffer.from(await res.arrayBuffer()));
  execFileSync('sips', ['--resampleWidth', '360', dest], { stdio: 'ignore' });
  fetched++;
}

const lines = [...paths]
  .sort()
  .map((p) => `  '${p}': require('../../assets/benchmark/img/${p.replace(/^img\//, '')}'),`);
writeFileSync(
  mapFile,
  `// Generated by scripts/benchmark/fetch-photos.mjs. Do not edit by hand.
// Photos: Free Exercise DB (github.com/yuhonas/free-exercise-db), public domain.
const PHOTOS: Record<string, number> = {
${lines.join('\n')}
};

export function photoSource(path: string | null | undefined): number | null {
  return path ? (PHOTOS[path] ?? null) : null;
}
`,
);
console.log(`${paths.size} photos referenced, ${fetched} downloaded → ${mapFile}`);
